-- 6. ROW LEVEL SECURITY
-- =====================================================================
alter table public.profiles  enable row level security;
alter table public.favorites enable row level security;
alter table public.progress  enable row level security;
alter table public.comments  enable row level security;

-- Elimina políticas antiguas (de tutoriales o versiones previas) para que el
-- estado de seguridad sea exactamente el que definimos aquí. Sin esto, una
-- política permisiva antigua podría anular las nuevas.
do $$
declare
    p record;
begin
    for p in
        select policyname, schemaname, tablename
          from pg_policies
         where schemaname = 'public'
           and tablename in ('profiles', 'favorites', 'progress', 'comments')
    loop
        execute format('drop policy if exists %I on %I.%I', p.policyname, p.schemaname, p.tablename);
    end loop;
end;
$$;

-- ---------------------------- profiles -------------------------------

   Tablas
     profiles   · nombre público de cada usuario
     favorites  · animes guardados en "Mi lista"
     progress   · punto de reproducción por episodio
     comments   · comentarios por anime

   Seguridad
     RLS activado en todas las tablas. Cada usuario solo puede escribir sus
     propias filas. Comentarios y perfiles son de lectura pública (la app
     necesita mostrar el nombre de quien comenta).

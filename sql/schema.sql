-- =====================================================================
-- 1. PERFILES
-- =====================================================================
create table if not exists public.profiles (
    id          uuid primary key references auth.users (id) on delete cascade,
    username    text not null,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now(),
    constraint profiles_username_len check (char_length(username) between 3 and 20)
);

-- Nombres únicos sin distinguir mayúsculas (@Ana y @ana no pueden coexistir)
create unique index if not exists profiles_username_lower_idx
    on public.profiles (lower(username));

-- Instalaciones antiguas pueden no tener created_at
alter table public.profiles add column if not exists created_at timestamptz not null default now();

-- Foto de perfil (la de Google) para mostrarla en los comentarios
alter table public.profiles add column if not exists avatar_url text;

-- =====================================================================
-- 2. FAVORITOS
-- =====================================================================
create table if not exists public.favorites (
    id          bigint generated by default as identity primary key,
    user_id     uuid not null references auth.users (id) on delete cascade,
    anime_id    text not null,
    created_at  timestamptz not null default now(),
    constraint favorites_unique unique (user_id, anime_id)
);

create index if not exists favorites_user_idx on public.favorites (user_id, created_at desc);

-- =====================================================================
-- 3. PROGRESO
-- =====================================================================
create table if not exists public.progress (
    id          bigint generated by default as identity primary key,
    user_id     uuid not null references auth.users (id) on delete cascade,
    anime_id    text not null,
    season_id   text not null,
    episode_id  text not null,
    position    integer not null default 0,
    duration    integer not null default 0,
    updated_at  timestamptz not null default now(),
    constraint progress_unique unique (user_id, episode_id)
);

create index if not exists progress_user_idx on public.progress (user_id, updated_at desc);

-- =====================================================================
-- 4. COMENTARIOS
-- =====================================================================
create table if not exists public.comments (
    id          bigint generated by default as identity primary key,
    user_id     uuid not null references auth.users (id) on delete cascade,
    anime_id    text,
    episode_id  text,
    content     text not null,
    created_at  timestamptz not null default now(),
    constraint comments_content_len check (char_length(content) between 1 and 500)
);

-- Compatibilidad con instalaciones antiguas que no tenían estas columnas
alter table public.comments add column if not exists anime_id  text;
alter table public.comments add column if not exists episode_id text;

create index if not exists comments_anime_idx on public.comments (anime_id, created_at desc);
create index if not exists comments_user_idx  on public.comments (user_id);

-- =====================================================================
-- 5. PERFIL AUTOMÁTICO AL REGISTRARSE
--    Así el usuario puede comentar justo después del login, sin tener
--    que abrir antes la pantalla de perfil.
-- =====================================================================
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    base      text;
    candidate text;
    suffix    integer := 0;
    photo     text;
begin
    base := coalesce(
        new.raw_user_meta_data ->> 'full_name',
        new.raw_user_meta_data ->> 'name',
        split_part(coalesce(new.email, ''), '@', 1),
        'usuario'
    );

    -- Limpia caracteres problemáticos y limita la longitud
    base := regexp_replace(base, '[^0-9A-Za-zÁÉÍÓÚÜÑáéíóúüñ ._-]', '', 'g');
    base := left(btrim(base), 20);
    if base is null or base = '' then
        base := 'usuario';
    end if;
    if char_length(base) < 3 then
        base := base || 'anon';
    end if;

    candidate := base;

    while exists (
        select 1 from public.profiles p where lower(p.username) = lower(candidate)
    ) loop
        suffix := suffix + 1;
        candidate := left(base, 15) || '_' || suffix::text;
        exit when suffix > 100;
    end loop;

    insert into public.profiles (id, username, avatar_url)
    values (
        new.id,
        candidate,
        nullif(coalesce(
            new.raw_user_meta_data ->> 'avatar_url',
            new.raw_user_meta_data ->> 'picture'
        ), '')
    )
    on conflict (id) do nothing;

    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.handle_new_user();

-- Rellena la foto de los perfiles creados antes de existir avatar_url
update public.profiles p
set avatar_url = coalesce(
        u.raw_user_meta_data ->> 'avatar_url',
        u.raw_user_meta_data ->> 'picture'
    )
from auth.users u
where u.id = p.id
  and (p.avatar_url is null or p.avatar_url = '')
  and coalesce(
        u.raw_user_meta_data ->> 'avatar_url',
        u.raw_user_meta_data ->> 'picture'
      ) is not null;

